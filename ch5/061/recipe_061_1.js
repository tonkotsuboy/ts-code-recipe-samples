// 書籍ではコールバック関数の構文テンプレート（要素・インデックス・元配列を受け取る形）を示しています。
// そのままでは実行できないため、配布コードではコメントでテンプレートを示したうえで、
// 動作が確認できる最小の実行例を添えています。
//
// ■ 書籍のテンプレート
//   ([要素], [インデックス], [元配列]) => {
//     // 処理
//   };
//
// ■ 実際に動かす例
const numbers = [1, 2, 3];
numbers.map((要素, インデックス, 元配列) => {
  console.log({ 要素, インデックス, 元配列 });
});
// { 要素: 1, インデックス: 0, 元配列: [ 1, 2, 3 ] }
// { 要素: 2, インデックス: 1, 元配列: [ 1, 2, 3 ] }
// { 要素: 3, インデックス: 2, 元配列: [ 1, 2, 3 ] }
